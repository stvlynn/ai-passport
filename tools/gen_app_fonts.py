#!/usr/bin/env python3
"""Generate the Astra Monitor pixel fonts (assets/fonts/ui_font_{12,24,36}.c).

Source font: Fusion Pixel Font 12px proportional, zh_hans build (SIL OFL 1.1),
https://github.com/TakWolf/fusion-pixel-font  (release 2026.10.25).
Converter:   lv_font_conv 1.5.2 (npm), 1 bpp, uncompressed; the LVGL symbol
             name is taken from the output file name.

Character inventory
  ui_font_12  printable ASCII + GB2312 level-1 hanzi (3755, covers common
              Chinese issue/PR titles) + CJK punctuation + every non-ASCII
              character used in main/*.c string literals.
  ui_font_24  printable ASCII + non-ASCII characters used in main/ui.c
              (page titles and headline text; 2x of the 12px grid).
  ui_font_36  digits and the few symbols used by the big star counter (3x).

Usage (from the repository root):
  python3 tools/gen_app_fonts.py --font <path>/fusion-pixel-12px-proportional-zh_hans.ttf
"""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "fonts"
APP_SOURCES = ["ui.c", "app_main.c", "gh_model.c", "app_console.c"]
PUNCT = "，。、：；！？「」『』（）·…—“”‘’《》【】～￥％＋－"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))


def gb2312_level1() -> str:
    chars = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes((hi, lo)).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return "".join(chars)


def literal_chars(files) -> set:
    found = set()
    for name in files:
        text = (ROOT / "main" / name).read_text(encoding="utf-8")
        # 只取字符串字面量,排除注释里的字。
        for lit in re.findall(r'"((?:[^"\\\n]|\\.)*)"', text):
            found.update(ch for ch in lit if ord(ch) > 0x7E)
    return found


def convert(font: Path, size: int, symbols: str, name: str) -> None:
    out = OUT / f"{name}.c"
    cmd = [
        "lv_font_conv", "--font", str(font), "--size", str(size), "--bpp", "1",
        "--format", "lvgl", "--no-compress",
        "--lv-include", "lvgl.h", "--symbols", symbols, "--output", str(out),
    ]
    subprocess.run(cmd, check=True)
    print(f"{name}: {len(set(symbols))} symbols -> {out.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True, type=Path)
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    used = literal_chars(APP_SOURCES)
    s12 = sorted(set(ASCII) | set(gb2312_level1()) | set(PUNCT) | used)
    s24 = sorted(set(ASCII) | literal_chars(["ui.c"]))
    s36 = "0123456789+-.,k"
    (OUT / "ui_font_inventory.txt").write_text(
        "# Generated by tools/gen_app_fonts.py; non-ASCII characters used by app strings.\n"
        + "".join(sorted(used)) + "\n", encoding="utf-8")
    convert(args.font, 12, "".join(s12), "ui_font_12")
    convert(args.font, 24, "".join(s24), "ui_font_24")
    convert(args.font, 36, s36, "ui_font_36")


if __name__ == "__main__":
    main()
