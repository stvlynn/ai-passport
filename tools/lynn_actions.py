def S(frame, t, lift=0, dx=0, hy=0, hx=0, flags=0, emote=None, hand=HAND_NONE):
    return dict(frame=frame, t=t, lift=lift, dx=dx, hy=hy, hx=hx, flags=flags, emote=emote, hand=hand)


def rep(n, *steps):
    return [dict(s) for _ in range(n) for s in steps]


def jump(frame, heights, emote=None):
    return [S(frame, 1, lift=h, emote=emote) for h in heights]


