"""Lynn stage actions: the single source of truth for animation timelines and agent tools.

Each action becomes
  - a timeline in main/lynn_stage_data.c (generated by tools/gen_lynn_stage.py),
  - an entry in docs/lynn-actions.json (the agent tool manifest),
  - a row in the docs.

Timing: the stage ticks at 24 fps. A step holds one drawing for `t` ticks (pixel-art holds on 2s/3s);
lift/dx/head offsets are in logical (64-grid) pixels. Idle activities have entry/loop/exit and loop a
random number of times; interactions play entry+loop+exit once (loop repeated `loops` times).
"""

